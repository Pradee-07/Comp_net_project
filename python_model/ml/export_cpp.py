"""
export_cpp.py -- Exports PyTorch TinyTTS model parameters to a standalone, zero-dependency C++ header.
The header includes complete forward inference with:
- Normalization & de-normalization
- Positional encoding
- Explicit multi-head self-attention
- Layer normalization & GELU feed-forward
- Dual head outputs: load prediction (Mbps) & risk probability [0, 1]
"""

import os
import torch
import numpy as np


def export_to_header(model, out_header_path):
    """
    Exports a trained TinyTTS PyTorch model to a self-contained C++ header.
    """
    model.eval()
    d_model = model.d_model
    num_heads = model.num_heads
    d_k = d_model // num_heads
    d_ff = model.d_ff
    seq_len = model.seq_len
    input_dim = model.input_dim

    # Ensure output directory exists
    os.makedirs(os.path.dirname(os.path.abspath(out_header_path)), exist_ok=True)

    # Extract tensors
    feat_mean = model.feat_mean.cpu().numpy()
    feat_std = model.feat_std.cpu().numpy()
    load_mean = float(model.load_mean.item())
    load_std = float(model.load_std.item())

    # Positional encoding: (1, max_len, d_model) -> take (seq_len, d_model)
    pe = model.pos_enc.pe[0, :seq_len, :].cpu().numpy()

    # Input projection
    w_in = model.input_proj.weight.detach().cpu().numpy() # (d_model, input_dim)
    b_in = model.input_proj.bias.detach().cpu().numpy()   # (d_model,)

    # Transformer block 0
    layer = model.layers[0]
    w_q = layer.attn.q_proj.weight.detach().cpu().numpy() # (d_model, d_model)
    b_q = layer.attn.q_proj.bias.detach().cpu().numpy()   # (d_model,)
    w_k = layer.attn.k_proj.weight.detach().cpu().numpy()
    b_k = layer.attn.k_proj.bias.detach().cpu().numpy()
    w_v = layer.attn.v_proj.weight.detach().cpu().numpy()
    b_v = layer.attn.v_proj.bias.detach().cpu().numpy()
    w_out = layer.attn.out_proj.weight.detach().cpu().numpy()
    b_out = layer.attn.out_proj.bias.detach().cpu().numpy()

    ln1_w = layer.ln1.weight.detach().cpu().numpy() # (d_model,)
    ln1_b = layer.ln1.bias.detach().cpu().numpy()

    ffn1_w = layer.ffn[0].weight.detach().cpu().numpy() # (d_ff, d_model)
    ffn1_b = layer.ffn[0].bias.detach().cpu().numpy()   # (d_ff,)
    ffn2_w = layer.ffn[3].weight.detach().cpu().numpy() # (d_model, d_ff)
    ffn2_b = layer.ffn[3].bias.detach().cpu().numpy()   # (d_model,)

    ln2_w = layer.ln2.weight.detach().cpu().numpy() # (d_model,)
    ln2_b = layer.ln2.bias.detach().cpu().numpy()

    # Heads
    w_head_load = model.head_load.weight.detach().cpu().numpy().flatten() # (d_model,)
    b_head_load = float(model.head_load.bias.item())
    w_head_risk = model.head_risk.weight.detach().cpu().numpy().flatten() # (d_model,)
    b_head_risk = float(model.head_risk.bias.item())

    def format_1d(arr):
        return ", ".join(f"{float(x):.8e}f" for x in arr)

    def format_2d(arr):
        lines = []
        for row in arr:
            lines.append("  { " + ", ".join(f"{float(x):.8e}f" for x in row) + " }")
        return ",\n".join(lines)

    header_content = f"""// Auto-generated by export_cpp.py -- Standalone Tiny-TTS Edge Transformer for NS-3 / C++
#ifndef TINY_TTS_WEIGHTS_H
#define TINY_TTS_WEIGHTS_H

#include <cmath>
#include <algorithm>

namespace TinyTTS {{

constexpr int D_INPUT = {input_dim};
constexpr int D_MODEL = {d_model};
constexpr int NUM_HEADS = {num_heads};
constexpr int D_K = {d_k};
constexpr int D_FF = {d_ff};
constexpr int SEQ_LEN = {seq_len};

// Normalization constants
static const float FEAT_MEAN[{input_dim}] = {{ {format_1d(feat_mean)} }};
static const float FEAT_STD[{input_dim}]  = {{ {format_1d(feat_std)} }};
constexpr float LOAD_MEAN = {load_mean:.8e}f;
constexpr float LOAD_STD  = {load_std:.8e}f;

// Positional Encoding (SEQ_LEN x D_MODEL)
static const float POS_ENC[{seq_len}][{d_model}] = {{
{format_2d(pe)}
}};

// Input projection: W_IN [D_MODEL][D_INPUT], B_IN [D_MODEL]
static const float W_IN[{d_model}][{input_dim}] = {{
{format_2d(w_in)}
}};
static const float B_IN[{d_model}] = {{ {format_1d(b_in)} }};

// Attention Q, K, V, Out projections: [D_MODEL][D_MODEL]
static const float W_Q[{d_model}][{d_model}] = {{
{format_2d(w_q)}
}};
static const float B_Q[{d_model}] = {{ {format_1d(b_q)} }};

static const float W_K[{d_model}][{d_model}] = {{
{format_2d(w_k)}
}};
static const float B_K[{d_model}] = {{ {format_1d(b_k)} }};

static const float W_V[{d_model}][{d_model}] = {{
{format_2d(w_v)}
}};
static const float B_V[{d_model}] = {{ {format_1d(b_v)} }};

static const float W_OUT[{d_model}][{d_model}] = {{
{format_2d(w_out)}
}};
static const float B_OUT[{d_model}] = {{ {format_1d(b_out)} }};

// LayerNorm 1
static const float LN1_GAMMA[{d_model}] = {{ {format_1d(ln1_w)} }};
static const float LN1_BETA[{d_model}]  = {{ {format_1d(ln1_b)} }};

// FFN: W1 [D_FF][D_MODEL], W2 [D_MODEL][D_FF]
static const float W_FFN1[{d_ff}][{d_model}] = {{
{format_2d(ffn1_w)}
}};
static const float B_FFN1[{d_ff}] = {{ {format_1d(ffn1_b)} }};

static const float W_FFN2[{d_model}][{d_ff}] = {{
{format_2d(ffn2_w)}
}};
static const float B_FFN2[{d_model}] = {{ {format_1d(ffn2_b)} }};

// LayerNorm 2
static const float LN2_GAMMA[{d_model}] = {{ {format_1d(ln2_w)} }};
static const float LN2_BETA[{d_model}]  = {{ {format_1d(ln2_b)} }};

// Output Heads
static const float W_HEAD_LOAD[{d_model}] = {{ {format_1d(w_head_load)} }};
constexpr float B_HEAD_LOAD = {b_head_load:.8e}f;

static const float W_HEAD_RISK[{d_model}] = {{ {format_1d(w_head_risk)} }};
constexpr float B_HEAD_RISK = {b_head_risk:.8e}f;

// Fast approximate GELU
inline float FastGELU(float x) {{
    constexpr float k0 = 0.7978845608028654f; // sqrt(2/pi)
    constexpr float k1 = 0.044715f;
    float cube = x * x * x;
    return 0.5f * x * (1.0f + std::tanh(k0 * (x + k1 * cube)));
}}

// In-place 1D LayerNorm
inline void ApplyLayerNorm(float vec[{d_model}], const float gamma[{d_model}], const float beta[{d_model}]) {{
    float sum = 0.0f;
    for (int d = 0; d < {d_model}; ++d) sum += vec[d];
    float mean = sum / float({d_model});

    float var = 0.0f;
    for (int d = 0; d < {d_model}; ++d) {{
        float diff = vec[d] - mean;
        var += diff * diff;
    }}
    float inv_std = 1.0f / std::sqrt(var / float({d_model}) + 1e-5f);

    for (int d = 0; d < {d_model}; ++d) {{
        vec[d] = (vec[d] - mean) * inv_std * gamma[d] + beta[d];
    }}
}}

/**
 * Predict -- Zero-dependency native C++ inference.
 * Input:
 *   input_window: 2D array of shape [SEQ_LEN][D_INPUT] (raw telemetry)
 * Outputs:
 *   pred_load: Continuous predicted load in Mbps at next tick
 *   pred_risk: Probability [0.0, 1.0] of impending congestion
 */
inline void Predict(const float input_window[{seq_len}][{input_dim}], float &pred_load, float &pred_risk) {{
    // 1. Input projection & Positional Encoding: [SEQ_LEN][D_MODEL]
    float h[{seq_len}][{d_model}];
    for (int t = 0; t < {seq_len}; ++t) {{
        // Normalize input feature vector
        float norm_x[{input_dim}];
        for (int i = 0; i < {input_dim}; ++i) {{
            norm_x[i] = (input_window[t][i] - FEAT_MEAN[i]) / (FEAT_STD[i] + 1e-6f);
        }}
        for (int d = 0; d < {d_model}; ++d) {{
            float val = B_IN[d];
            for (int i = 0; i < {input_dim}; ++i) {{
                val += W_IN[d][i] * norm_x[i];
            }}
            h[t][d] = val + POS_ENC[t][d];
        }}
    }}

    // 2. Multi-Head Self-Attention
    float Q[{seq_len}][{d_model}], K[{seq_len}][{d_model}], V[{seq_len}][{d_model}];
    for (int t = 0; t < {seq_len}; ++t) {{
        for (int d = 0; d < {d_model}; ++d) {{
            float q_val = B_Q[d];
            float k_val = B_K[d];
            float v_val = B_V[d];
            for (int j = 0; j < {d_model}; ++j) {{
                q_val += W_Q[d][j] * h[t][j];
                k_val += W_K[d][j] * h[t][j];
                v_val += W_V[d][j] * h[t][j];
            }}
            Q[t][d] = q_val;
            K[t][d] = k_val;
            V[t][d] = v_val;
        }}
    }}

    // Scaled dot-product attention per head
    float context[{seq_len}][{d_model}] = {{0}};
    float scale = 1.0f / std::sqrt(float({d_k}));

    for (int head = 0; head < {num_heads}; ++head) {{
        int head_offset = head * {d_k};
        for (int i = 0; i < {seq_len}; ++i) {{
            float scores[{seq_len}];
            float max_score = -1e9f;
            for (int j = 0; j < {seq_len}; ++j) {{
                float dot = 0.0f;
                for (int m = 0; m < {d_k}; ++m) {{
                    dot += Q[i][head_offset + m] * K[j][head_offset + m];
                }}
                scores[j] = dot * scale;
                if (scores[j] > max_score) max_score = scores[j];
            }}

            // Softmax
            float sum_exp = 0.0f;
            for (int j = 0; j < {seq_len}; ++j) {{
                scores[j] = std::exp(scores[j] - max_score);
                sum_exp += scores[j];
            }}
            float inv_sum = 1.0f / (sum_exp + 1e-9f);
            for (int j = 0; j < {seq_len}; ++j) {{
                scores[j] *= inv_sum;
            }}

            // Attention @ V
            for (int m = 0; m < {d_k}; ++m) {{
                float weighted_v = 0.0f;
                for (int j = 0; j < {seq_len}; ++j) {{
                    weighted_v += scores[j] * V[j][head_offset + m];
                }}
                context[i][head_offset + m] = weighted_v;
            }}
        }}
    }}

    // Out projection + Residual + LayerNorm 1
    float h_att[{seq_len}][{d_model}];
    for (int t = 0; t < {seq_len}; ++t) {{
        for (int d = 0; d < {d_model}; ++d) {{
            float out_val = B_OUT[d];
            for (int j = 0; j < {d_model}; ++j) {{
                out_val += W_OUT[d][j] * context[t][j];
            }}
            h_att[t][d] = h[t][d] + out_val; // Residual
        }}
        ApplyLayerNorm(h_att[t], LN1_GAMMA, LN1_BETA);
    }}

    // 3. FFN + Residual + LayerNorm 2
    float h_final[{seq_len}][{d_model}];
    for (int t = 0; t < {seq_len}; ++t) {{
        float ffn1[{d_ff}];
        for (int f = 0; f < {d_ff}; ++f) {{
            float val = B_FFN1[f];
            for (int d = 0; d < {d_model}; ++d) {{
                val += W_FFN1[f][d] * h_att[t][d];
            }}
            ffn1[f] = FastGELU(val);
        }}
        for (int d = 0; d < {d_model}; ++d) {{
            float val = B_FFN2[d];
            for (int f = 0; f < {d_ff}; ++f) {{
                val += W_FFN2[d][f] * ffn1[f];
            }}
            h_final[t][d] = h_att[t][d] + val; // Residual
        }}
        ApplyLayerNorm(h_final[t], LN2_GAMMA, LN2_BETA);
    }}

    // 4. Last token representation
    const float* z_last = h_final[{seq_len} - 1];

    // 5. Prediction heads
    float norm_pred_load = B_HEAD_LOAD;
    float risk_logit = B_HEAD_RISK;
    for (int d = 0; d < {d_model}; ++d) {{
        norm_pred_load += W_HEAD_LOAD[d] * z_last[d];
        risk_logit += W_HEAD_RISK[d] * z_last[d];
    }}

    // De-normalize load & sigmoid for risk
    pred_load = norm_pred_load * (LOAD_STD + 1e-6f) + LOAD_MEAN;
    pred_risk = 1.0f / (1.0f + std::exp(-risk_logit));
}}

}} // namespace TinyTTS

#endif // TINY_TTS_WEIGHTS_H
"""

    with open(out_header_path, "w") as f:
        f.write(header_content)
    print(f"  ✓ Exported pure C++ weights header to: {out_header_path}")
